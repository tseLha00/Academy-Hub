CREATE TABLE training_comments (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   assignment_id BIGINT NOT NULL,
                                   author_id BIGINT NOT NULL,

                                   content TEXT NOT NULL,
                                   created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   CONSTRAINT fk_training_comments_assignment
                                       FOREIGN KEY (assignment_id)
                                           REFERENCES training_assignments(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT fk_training_comments_author
                                       FOREIGN KEY (author_id)
                                           REFERENCES users(id)
                                           ON DELETE RESTRICT,

                                   CONSTRAINT chk_training_comments_content
                                       CHECK (LENGTH(TRIM(content)) > 0)
);

CREATE INDEX idx_training_comments_assignment_created
    ON training_comments (assignment_id, created_at, id);