CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       display_name VARCHAR(150) NOT NULL,
                       role VARCHAR(20) NOT NULL,

                       CONSTRAINT chk_users_display_name_not_blank
                           CHECK (length(trim(display_name)) > 0),

                       CONSTRAINT chk_users_role
                           CHECK (role IN ('LEARNER', 'ADMIN'))
);

CREATE TABLE trainings (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(200) NOT NULL,
                           created_by BIGINT NOT NULL,

                           CONSTRAINT chk_trainings_name_not_blank
                               CHECK (length(trim(name)) > 0),

                           CONSTRAINT fk_trainings_creator
                               FOREIGN KEY (created_by) REFERENCES users (id)
);

CREATE TABLE training_assignments (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      training_id BIGINT NOT NULL,
                                      learner_id BIGINT NOT NULL,
                                      completed_at TIMESTAMP WITH TIME ZONE,

                                      CONSTRAINT fk_training_assignments_training
                                          FOREIGN KEY (training_id) REFERENCES trainings (id),

                                      CONSTRAINT fk_training_assignments_learner
                                          FOREIGN KEY (learner_id) REFERENCES users (id),

                                      CONSTRAINT uq_training_assignments_training_learner
                                          UNIQUE (training_id, learner_id)
);

CREATE INDEX idx_trainings_created_by
    ON trainings (created_by);

CREATE INDEX idx_training_assignments_learner_id
    ON training_assignments (learner_id);